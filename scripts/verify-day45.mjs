import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { VoteLoop } from '../src/loop.ts';
import { createApp } from '../src/server.ts';
import { replay } from '../src/replay.ts';
import { configuredBrain } from '../src/brain.ts';
import { HttpHelix } from '../src/helix.ts';
import { fakeHelix } from '../test/helpers/fake-helix.ts';
const fake = await fakeHelix();
const helix = new HttpHelix({ baseUrl: fake.baseUrl, clientId: 'fake-client', token: async () => 'fake-token', broadcasterId: 'channel-test', moderatorId: 'mod' });
let now = Date.now();
const loop = new VoteLoop({ now: () => now, helix, brain: configuredBrain() });
const app = createApp(loop, { tick: false });
await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${app.server.address().port}`;
const target = await (await fetch('http://127.0.0.1:9252/json/new?about:blank', { method: 'PUT' })).json();
const ws = new WebSocket(target.webSocketDebuggerUrl);
await new Promise(resolve => ws.addEventListener('open', resolve, { once: true }));
let next = 0; const pending = new Map();
ws.addEventListener('message', event => { const m = JSON.parse(event.data); const p = pending.get(m.id); if (p) { pending.delete(m.id); m.error ? p.reject(new Error(m.error.message)) : p.resolve(m.result); } });
const send = (method, params = {}) => new Promise((resolve, reject) => { const id = ++next; pending.set(id, { resolve, reject }); ws.send(JSON.stringify({ id, method, params })); });
const evaluate = async expression => { const r = await send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true }); if(r.exceptionDetails) throw new Error(r.exceptionDetails.text); return r.result.value; };
const wait = expression => evaluate(`new Promise((resolve,reject)=>{let n=0;const t=setInterval(()=>{if(${expression}){clearInterval(t);resolve(true)}else if(n++>50){clearInterval(t);reject(new Error('Operator timed out'))}},100)})`);
const key = async (key, code) => { await send('Input.dispatchKeyEvent', { type: 'keyDown', key, code }); await send('Input.dispatchKeyEvent', { type: 'keyUp', key, code }); };
try {
  await send('Page.enable');
  await send('Emulation.setDeviceMetricsOverride', { width: 1920, height: 1080, deviceScaleFactor: 1, mobile: false });
  await send('Page.navigate', { url: `${base}/operator` });
  await wait("document.getElementById('connection')?.textContent === '● Connected'");
  const ratio = await evaluate('innerWidth / 1920');
  if (ratio !== 1) await send('Emulation.setDeviceMetricsOverride', { width: Math.round(1920 / ratio), height: Math.round(1080 / ratio), deviceScaleFactor: ratio, mobile: false });
  assert.equal(await evaluate('innerWidth'), 1920); assert.equal(await evaluate('innerHeight'), 1080);
  await replay(loop, { now: () => now, sleep: async ms => { now += ms; }, runId: 'browser-keys' });
  await wait("document.getElementById('phase')?.textContent === 'VOTING'");
  await key(' ', 'Space');
  await wait("document.getElementById('phase')?.textContent === 'AWAITING APPROVAL'");
  await key('a', 'KeyA');
  await wait("document.getElementById('pending')?.textContent.startsWith('Approval queued')");
  now += 300; loop.tick(); await loop.flush();
  assert.equal(loop.snapshot().current.effects.timeout.status, 'sent');
  assert.equal(loop.snapshot().current.analysis.source, 'fallback');
  now += 3000; loop.tick(); await loop.flush();
  now += 120000; loop.tick(); await loop.flush();
  assert.equal(loop.snapshot().current.state, 'closed');
  await replay(loop, { now: () => now, sleep: async ms => { now += ms; }, runId: 'appeal-case' });
  await wait("document.getElementById('phase')?.textContent === 'VOTING'");
  await key(' ', 'Space');
  await wait("document.getElementById('phase')?.textContent === 'AWAITING APPROVAL'");
  await key('a', 'KeyA');
  await wait("document.getElementById('pending')?.textContent.startsWith('Approval queued')");
  now += 300; loop.tick(); await loop.flush();
  now += 3000; loop.tick(); await loop.flush();
  await wait("document.getElementById('phase')?.textContent === 'APPEAL WINDOW'");
  await evaluate("document.getElementById('demo-appeal').click()");
  await wait("!document.getElementById('overturn').disabled");
  await evaluate("document.getElementById('overturn').click()");
  await wait("document.getElementById('phase')?.textContent === 'CLOSED'");
  await loop.flush();
  assert.equal(loop.snapshot().current.effects.release.status, 'sent');
  assert.equal(loop.snapshot().consistency, 0);
  assert.equal(fake.calls.filter(c => c.method === 'DELETE').length, 1);
  assert.equal(fake.calls.filter(c => c.path.endsWith('/messages')).length, 3);
  await send('Page.navigate', { url: `${base}/docket` });
  await wait("document.getElementById('consistency')?.textContent === '0% agreement'");
  assert.match(await evaluate("document.getElementById('cases').textContent"), /Appeal overturned/);
  assert.match(await evaluate("document.getElementById('cases').textContent"), /Advice from fallback/);
  assert.equal(await evaluate("document.querySelectorAll('#cases article').length"), 2);
  const metrics = await send('Page.getLayoutMetrics');
  const shot = await send('Page.captureScreenshot', { format: 'png', captureBeyondViewport: true, clip: { x: 0, y: 0, width: metrics.cssContentSize.width, height: metrics.cssContentSize.height, scale: 1 } });
  await writeFile('docs/screenshots/day45-docket.png', Buffer.from(shot.data, 'base64'));
  console.log('G5 passed with an empty model key. Fake Helix timeout, verdict, appeal release and docket score passed.');
} finally {
  ws.close(); await fetch(`http://127.0.0.1:9252/json/close/${target.id}`);
  await app.stop(); loop.dispose(); await fake.close();
}
